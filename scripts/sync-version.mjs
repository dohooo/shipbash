// Runs from the `version` lifecycle (after `bun pm version` bumps the root
// package.json, before it commits) and on demand: the root version is the
// only version. Every workspace package, the lockfile and the generated
// `@shipbash/contracts/version` module follow it; the CLI package stays on
// changesets and is left alone.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const FOLLOWERS = [
  "packages/contracts/package.json",
  "packages/control-plane/package.json",
  "packages/runner/package.json",
  "apps/console/package.json",
  "apps/marketing/package.json",
];
const VERSION_MODULE = "packages/contracts/src/version.ts";

const { version } = JSON.parse(readFileSync("package.json", "utf8"));
if (!/^\d+\.\d+\.\d+$/u.test(version)) {
  console.error(`The root package.json version is not a release version: ${version}`);
  process.exit(1);
}

// Workspace packages depend on each other through `workspace:*`, so only
// their version fields move.
for (const path of FOLLOWERS) {
  const next = readFileSync(path, "utf8").replace(/^(\s*"version":\s*")[^"]+(")/mu, `$1${version}$2`);
  if (!next.includes(`"version": "${version}"`)) {
    console.error(`${path} carries no version field to update.`);
    process.exit(1);
  }
  writeFileSync(path, next);
}

writeFileSync(VERSION_MODULE, [
  "// Generated by scripts/sync-version.mjs from the root package.json; do not edit.",
  `export const SHIPBASH_VERSION = "${version}";`,
  "",
].join("\n"));

execFileSync("bun", ["install", "--lockfile-only"], { stdio: "inherit" });
execFileSync("git", ["add", "bun.lock", VERSION_MODULE, ...FOLLOWERS], { stdio: "inherit" });
console.log(`Every package now reports ${version}.`);
